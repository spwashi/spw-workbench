#!/usr/bin/env tsx
/**
 * The act chain table: every ordered pair of the twelve marks, written against an
 * operand in each position a chain can take, and how the parser reads it today.
 *
 *   npm run analyze:act-chains            print the tables
 *   npm run analyze:act-chains -- --write regenerate docs/theory/spw/act-chains-today.spw
 *   npm run analyze:act-chains -- --check  fail when the committed table differs from the parser
 *
 * Positions: prefix XYname, postfix nameXY (and nameXY next, to show what a word
 * after it does), infix aXYb, and the container family X[x], XY[x], X[x]Y, [x]XY.
 * Each cell is the class of the tree the parser builds, read from the tree itself
 * (docs/theory/spw/act-chains.spw holds the legend and the model). The committed
 * table is a fixture: a parser change that moves a cell shows here as a diff.
 */
import { promises as fs } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { lex, multiCharacterMarks, parse } from '../../packages/spw-seed/src/index'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const OUT = path.join(root, 'docs/theory/spw/act-chains-today.spw')
export const MARKS = ['!', '^', '~', '?', '*', '=', '@', '#', '.', '&', '$', '%'] as const

/** The classes a reading falls in; the legend in act-chains.spw says what each means. */
export const CLASSES = {
  C: 'chain: one expression holds both marks and the operand',
  S: 'split: the marks stand as separate statements',
  P: 'prose: the first mark takes the rest of the line as text',
  K: 'particle: the lexer fuses the pair into one token',
  F: 'fused: the lexer reads the pair as one connector or comparison',
  J: 'subject: the second mark turns the operand into the first mark\'s subject',
  A: 'absorbed: a mark vanishes into the operand, or from the tree',
  M: 'modifier: a trailing bare mark takes the next spaced word',
  B: 'bullet: the pair opens a list item',
  W: 'warning: the parser reads it with a warning',
  E: 'error: the parser reports an error',
} as const
export type ChainClass = keyof typeof CLASSES

function classify(src: string): ChainClass {
  const tokens = lex(src).tokens.filter((t: any) => t.type !== 'EOF' && t.type !== 'WHITESPACE')
  const r: any = parse(src)
  if (r.errors.length) return 'E'
  if (r.warnings.length || r.ast.expression?.type === 'Prose') return 'W'
  if (tokens.some((t: any) => t.type === 'PARTICLE')) return 'K'
  if (tokens.some((t: any) => t.type === 'CONNECTOR' && t.value.length > 1) || tokens.some((t: any) => t.type === 'COMPARISON')) {
    return JSON.stringify(r.ast).includes('"Bullet"') ? 'B' : 'F'
  }
  const tree = JSON.stringify(r.ast.expression)
  if (tree.includes('linePayload')) return 'P'
  if (tree.includes('"ModifierChain"')) return 'M'
  // Every mark written should appear in the tree; one that does not was absorbed or lost. An @ before a
  // name is kept as the Reference node it becomes, not as an operator token.
  const written = tokens.filter((t: any) => t.type === 'OPERATOR').length
  const kept = (tree.match(/"type":"OPERATOR"/g) ?? []).length + (tree.match(/"type":"Reference"/g) ?? []).length
  if (kept < written) return 'A'
  if (tree.includes('"subject"')) return 'J'
  const statements = r.ast.expression?.expressions?.length ?? 1
  return statements > 1 ? 'S' : 'C'
}

export const POSITIONS = {
  prefix: (a: string, b: string) => `${a}${b}name`,
  postfix: (a: string, b: string) => `name${a}${b}`,
  postfix_then_word: (a: string, b: string) => `name${a}${b} next`,
  infix: (a: string, b: string) => `left${a}${b}right`,
  pair_on_frame: (a: string, b: string) => `${a}${b}[x]`,
  around_frame: (a: string, b: string) => `${a}[x]${b}`,
  after_frame: (a: string, b: string) => `[x]${a}${b}`,
} as const

export function actChainTable(): Record<keyof typeof POSITIONS, Record<string, ChainClass>> {
  const table = {} as Record<keyof typeof POSITIONS, Record<string, ChainClass>>
  for (const [position, form] of Object.entries(POSITIONS) as Array<[keyof typeof POSITIONS, (a: string, b: string) => string]>) {
    table[position] = {}
    for (const a of MARKS) for (const b of MARKS) table[position][a + b] = classify(form(a, b))
  }
  return table
}

/** One position as twelve rows, each a first mark and the classes for the twelve second marks. */
function rows(cells: Record<string, ChainClass>): string[] {
  return MARKS.map((a) => ` ${JSON.stringify(a)}: "${MARKS.map((b) => cells[a + b]).join(' ')}"`)
}

export function renderTable(table = actChainTable()): string {
  const fused = multiCharacterMarks()
  const out = [
    '# Act chains today — how the parser reads every ordered pair of marks, by position',
    '#',
    '# Generated by scripts/analyzers/act-chain-table.ts (npm run analyze:act-chains -- --write); do not edit.',
    '# Each row is a first mark; its twelve classes follow the second mark in the column order below.',
    '# The legend and the model are in act-chains.spw. A parser change that moves a cell shows as a diff here.',
    '',
    '#>act_chains_today',
    '#:layer #!syntax',
    '#:status #!measured',
    '',
    '^["columns"]{',
    ` order: "${MARKS.join(' ')}"`,
    ` fused_by_the_lexer: "${fused.join(' ')}"`,
    '}',
    '',
    '^["legend"]{',
    ...Object.entries(CLASSES).map(([k, v]) => ` ${k}: "${v}"`),
    '}',
  ]
  for (const [position, form] of Object.entries(POSITIONS)) {
    out.push('', `^["${position}"]{`, ` form: \`${form('X', 'Y')}\``, ...rows(table[position as keyof typeof POSITIONS]), '}')
  }
  // A summary per position, so a reader sees how far the table is from one class.
  out.push('', '^["summary"]{')
  for (const position of Object.keys(POSITIONS)) {
    const counts: Record<string, number> = {}
    for (const c of Object.values(table[position as keyof typeof POSITIONS])) counts[c] = (counts[c] ?? 0) + 1
    out.push(` ${position}: "${Object.entries(counts).sort((x, y) => y[1] - x[1]).map(([c, n]) => `${c} ${n}`).join(', ')}"`)
  }
  out.push('}', '')
  return out.join('\n')
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])
if (isMain) {
  const text = renderTable()
  if (process.argv.includes('--write')) {
    await fs.writeFile(OUT, text)
    console.log(`wrote ${path.relative(process.cwd(), OUT)}`)
  } else if (process.argv.includes('--check')) {
    const committed = await fs.readFile(OUT, 'utf8').catch(() => '')
    if (committed !== text) {
      console.error(`${path.relative(process.cwd(), OUT)} differs from what the parser reads now; regenerate with --write and read the diff`)
      process.exit(1)
    }
    console.log('act chain table current')
  } else {
    console.log(text)
  }
}
